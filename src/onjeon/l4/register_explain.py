"""등기부 판정 결과 → 한 문단 설명. **선택 경로 — 없으면 화면은 그대로 동작한다.**

LLM이 하는 일은 서술뿐이다. 등급과 항목은 `l3.register_risk`가 룰 테이블로 이미
정했고 여기서 바꾸지 않는다(원칙 1). 항목별 '왜/무엇을 확인'은 룰 JSON에 있어서
검증 가능하고 비용이 0이다 — LLM이 더하는 건 '이 조합이 무슨 뜻인가' 한 문단뿐이라
기본이 꺼짐이다.

키가 없거나(`make_llm()` → None) SDK가 없거나(컨테이너는 `requirements-api.txt`만
설치하므로 google-genai가 없다) 호출이 실패하면 **None**을 돌려준다. 호출측은 이
필드를 응답에서 빼기만 하면 되고, 등급·항목은 LLM 없이 이미 완성돼 있다.
"""

from __future__ import annotations

from onjeon.llm import make_llm

SYSTEM = """너는 온전(穩全)의 등기부 판독 결과를 설명하는 서술기다.

계산도 판정도 하지 않는다. 등급과 위험요소 목록은 이미 결정론 코드가 정했고,
너는 그것을 청년 임차인이 읽을 수 있는 한 문단으로 옮긴다.

절대 금지:
- 등급을 바꾸거나 다르게 표현하는 것 (주어진 등급 그대로)
- 입력에 없는 위험요소를 추가하는 것
- 숫자를 만드는 것 — 시세·전세가율·사고확률·기대손실·보증금 회수액을 언급하지 않는다.
  입력에 있는 금액만 그대로 옮긴다
- 임대인의 신용·체납·의도를 추정하는 것
- 계약을 권유하거나 만류하는 것 ("계약하지 마세요"·"안전합니다" 금지)
- 보증보험 가입 가능/불가를 단정하는 것

문장 규칙:
- 3~5문장. 존댓말, 과장 금지, 이모지 금지
- 각 위험요소를 말할 때 위치를 함께 쓴다 (예: "갑구 3번, 2024년 5월 17일 접수")
- 등급이 '판정 보류'면 등급 대신 왜 판정할 수 없는지와 무엇을 하면 판정되는지를 쓴다
- 마지막 문장은 사용자가 다음에 할 행동 하나로 끝낸다"""


def explain(risk: dict, warnings: list[str] | None = None) -> str | None:
    """판정 결과 → 3~5문장. 실패하면 None (호출측은 필드를 빼기만 한다)."""
    llm = make_llm()
    if llm is None:
        return None
    lines = [
        f"- {i['key']} · {i['section']} {i.get('rank') or '순위번호 미상'}"
        f" · {i.get('date') or '접수일 미상'} · {i['why']} → {i['action']}"
        for i in risk["items"]
    ]
    prompt = "\n".join(
        [
            f"등급: {risk['grade']} ({risk['label']})",
            f"판정 참고: {risk['note'] or '없음'}",
            "",
            "발견된 위험요소:",
            *(lines or ["- 없음"]),
            "",
            "이 문서로 확인할 수 없는 것(이미 판단된 한계, 그대로 반영하라):",
            *([f"- {w}" for w in warnings or []] or ["- 없음"]),
            "",
            "위 내용을 3~5문장으로 설명하라. 목록에 없는 것은 쓰지 마라.",
        ]
    )
    try:
        return llm.complete(prompt, system=SYSTEM).strip() or None
    except Exception:
        # 설명은 곁가지다. 키 오류·타임아웃·SDK 미설치 어느 것도 업로드 응답을
        # 깨뜨려선 안 된다 — 등급과 항목은 이 호출 없이 이미 완성돼 있다.
        return None
